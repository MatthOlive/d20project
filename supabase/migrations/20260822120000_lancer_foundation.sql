  to authenticated;
grant execute on function public.commit_lancer_entity_state(uuid, bigint, text, jsonb, jsonb, jsonb)
  to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'lancer_entities'
  ) then
    alter publication supabase_realtime add table public.lancer_entities;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'lancer_game_events'
  ) then
    alter publication supabase_realtime add table public.lancer_game_events;
  end if;
end $$;

